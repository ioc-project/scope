#!/usr/bin/env python3
"""Build a self-contained HTML page showing how claims flow through a session.

Reads the extraction output (``output/<session_id>.json``, which has the claims of each
LLMCall and its ``input_claims``) and, to know which agent made each call, the saved
trajectory (``input/trajectory_<session_id>.json``). No dependency beyond the standard library.

    python scripts/claims_graph.py output/<session_id>.json [-o page.html] [--trajectory PATH]

Layout: one swim lane per agent, one column per LLM call in time order. A call box holds the
claims it generated (cards coloured by agent). An arrow goes from a claim to every LLM call that
received it in its input (``input_claims``). By default only the calls where a claim *enters* an
agent call's context are linked (the first call of an agent call, or claims new since the
previous call of the same agent call); "all links" shows every presence. Click a claim to follow
it: its arrows are highlighted and the side panel lists where it was produced and consumed.

When the claims have ``same_claims`` (the input claims they restate, added by the embedding
comparison), a dashed red line joins each claim to the earlier claim it restates (checkbox
"same-claim links"). Unlike the arrows, these join two claims, not a claim and a call.

When the LLM calls have ``input_facts`` (tool results present in their input), each call box
lists them as dashed teal chips (checkbox "input facts"). Facts come from tool calls, which are
not columns of the page, so a chip stands for the tool result: click it to see the text, the
tool and agent that produced it, and every LLM call that had it in its input.

A fact is also "in context" of every claim generated by an LLM call that had it in its input
(the extractor's ``in_context`` relation, Fact -> Claim). Click a fact chip and those claims are
outlined in dashed teal (the others dim) and listed in the side panel; click a claim and the
facts that were in the context of its call are outlined.

When the claims have ``supported_by`` (the facts that support a claim, judged by
``FactClaimLinker`` in a live extraction), a claim card shows "supported by: <tool>" (checkbox
"supported-by facts"). The relation is stronger than ``in_context``, so it is outlined in solid
teal: select a fact to see the claims it supports, or a claim to see its facts; both are also
listed in the side panel.

When the claims have the relations of ``ClaimRelationExtractor`` (``conflicts_with``, ``same_as``,
``derived_from``: the input claims a new claim conflicts with, restates, or is derived from), a line
joins the two claims: solid red for a conflict, dotted violet for "same as" (the LLM judgement,
not the embedding-based ``same_claims``), and solid green with an arrowhead for "derived from"
(the arrowhead is on the claim it is derived from). Each has its own checkbox, a claim card lists its
relations, and selecting a claim highlights its partners and lists them in the side panel.

Claims are linked through the call that consumes them, since the extractor does not say which
input claim a new claim derives from (``derived_from`` says it, when the relation extractor ran).

When the output has goals (``symbolic_state_elements.goals`` on the ``Conversation`` node), a purple
"Goal" box is shown before the first call of the first agent, in that agent's lane, with a dotted
line to that call. Click it to see the success criteria, status and the user request / final
response it was read from.

When the AgentCall nodes have tasks (``symbolic_state_elements.tasks``), each task is shown as an
orange chip at the top of the first LLM call of its agent call (an agent call has no column of its
own). Click it to see the acceptance criteria, status and the LLM calls of that agent call.
When the tasks have ``same_as`` (the earlier identical tasks of other agent calls), a dotted orange
line joins each task to them (checkbox "same tasks").
When the tasks have ``implements`` (the tasks of an earlier agent call that a task carries out), a
solid orange arrow goes from the task to that task (checkbox "implements"). When they have
``achieves`` (the goal that a task achieves), a solid violet arrow goes from the task to the goal
card (checkbox "achieves").
When the claims have ``answers`` (the goals that a claim of the final answer answers), a fuchsia
dashed arrow goes from the claim to the goal card (checkbox "answers").
The status of the goal (``set`` / ``achieved`` / ``abandoned``, after the judgement of the final
answer when there is one) is a coloured badge on the goal card. A claim whose ``fulfils`` lists the
goal (it satisfies it) is marked on its card with a green "satisfies the goal" line; no arrow.
When the claims have ``produced_by`` (the task of the agent call whose LLM call generated them), the
card shows a "produced by task: ..." line, an attribute, no arrow (checkbox "produced by"). When
they have ``fulfils_task`` (the claims that fulfil the task they were produced by, judged by
``TaskClaimRelationExtractor``), a solid amber arrow goes from the claim to the task chip (checkbox
"fulfils task"); the card also says "fulfils the task".
When the tasks have ``preceded_by`` (the raw order: the tasks of the preceding agent call), a thin
grey dashed arrow goes from each of them to the task (checkbox "preceded by"), whatever the
``implements`` judgement says.
When the AgentCall nodes have delegation claims (``symbolic_state_elements.delegation_claims``: the claims
of the brief an agent sent when it delegated), they are listed in a "brief from <caller>" block at the top
of the first LLM call of the receiving agent call, as dashed cards coloured by the caller. They take part in
the claim-claim relations (conflicts, same as, derived from) like the other claims, and their side panel
lists the brief and the source claims (``source_claims``) they could restate.
When the output has system tasks (``symbolic_state_elements.system_tasks``), a second tab "System tasks"
shows them per agent, with the system prompt they were read from. No relations are drawn there.
When the output has constraints (``symbolic_state_elements.constraints``), the user constraints are shown
as rose chips under the goal they bound (``bounded_by``) in the goal box (dashed border when soft), the
system constraints of an agent (read from its system prompt) in its card of the second tab (renamed
"System tasks and constraints"), where each item carries a "task" (orange) or "constraint" (rose) tag, and a
task lists in its side panel the system constraints that bound it. Each constraint shows its strength
(hard / soft). No arrows: the goal card and the task chip only say how many constraints bound them.
When the output has capabilities (``symbolic_state_elements.capabilities``: what an agent is able to do, read
from its system prompt) they are listed in the same card of the second tab, with a "capability" tag (blue),
next to the standing tasks and the constraints (the tab is then renamed "System tasks, constraints and
capabilities"). No arrows. When a task or a standing task was judged against the capabilities of its agent
(``supported_by_capabilities``, the ``supports`` relation), the capabilities that support it are listed in
the task's side panel and under the standing task in the second tab, and a capability chip says which
tasks it supports.

The page is built from the nodes and the edges of the output (``nodes`` with their ``symbolic_state_elements``,
and ``edges``: every relation between two ids), not from the attributes the nodes also carry for each relation.
An output without ``edges`` (written before they existed) must be extracted again. The code is in the
``claims_page`` package next to this script: ``graph.py`` (the output as a graph), ``payload.py`` (what the page
shows, from it), ``render.py`` and ``template.html`` (the page itself).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from claims_page.payload import build_payload  # noqa: E402
from claims_page.render import render_html  # noqa: E402


def _load_json(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description="HTML view of the claims and their flow between LLM calls"
    )
    parser.add_argument(
        "output", type=Path, help="Extraction output JSON (output/<session_id>.json)"
    )
    parser.add_argument(
        "-o",
        "--out",
        type=Path,
        help="HTML path (default: next to the output, <session_id>_claims.html)",
    )
    parser.add_argument(
        "--trajectory",
        type=Path,
        help="Saved trajectory (default: input/trajectory_<session_id>.json, searched next to the output's parent)",
    )
    args = parser.parse_args(argv)

    output = _load_json(args.output)
    session_id = output.get("session_id", args.output.stem)
    trajectory_path = (
        args.trajectory
        or args.output.resolve().parent.parent / "input" / f"trajectory_{session_id}.json"
    )
    trajectory = None
    if trajectory_path.exists():
        trajectory = _load_json(trajectory_path)
    else:
        print(
            f"warning: no trajectory at {trajectory_path}; agents and agent calls are unknown",
            file=sys.stderr,
        )

    try:
        payload = build_payload(output, trajectory)
    except ValueError as exc:
        sys.exit(f"{args.output}: {exc}")
    out = args.out or args.output.with_name(f"{session_id}_claims.html")
    out.write_text(render_html(payload), encoding="utf-8")
    n_claims = sum(len(c["claims"]) for c in payload["calls"])
    print(
        f"Wrote {out} ({len(payload['calls'])} LLM calls, {n_claims} claims, agents: {', '.join(payload['agents'])})"
    )


if __name__ == "__main__":
    main()
