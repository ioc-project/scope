"""Claims made in the brief an agent sends to another agent when it delegates work.

When an agent delegates (``delegate_to_<agent>``), the text it gives the receiving agent is written
by the LLM of the caller: it restates findings ("Root cause: ...", "all dependencies are healthy"),
and that is the information that really travels between the agents. The trace does not keep it
where it was generated (the tool-call arguments are not recorded, and the output of the call is
often only a reference); it survives only as the input of the receiving AgentCall. So these claims
are extracted from the input of an AgentCall, and linked to the caller:

* ``generated_by``: the LLM call of the caller that delegated (``mas:generatedBy``);
* ``caller_agent`` / ``caller_call``: the agent and its AgentCall;
* ``delegated_to``: the AgentCall that received the brief (the node the claim is listed on).

They are a different kind (key ``delegation_claims``), not ``claims``: their ``verbatim_source`` is an
excerpt of the brief, not of the output of the LLM call they are linked to, so the checks and the
tracking that assume the latter must not see them.

Who the caller is (``find_caller``): the LLM call that delegated is the last one that ended before
the receiving call started, among the LLM calls of the agent calls whose output is a delegation
command (``delegate_to_x``, ``transfer_to_x``). Parallel delegations of one LLM turn run one after
the other, so the briefs of the later ones are found the same way.

No LLM request is made (``skip_reason``) when the call carries no brief of its own, judged on the
content and not on the format of the input:

* no caller: the first call of a session (the user request);
* an empty input or a bare resume marker (``sre-u1-exec-resume-2``);
* ``relay``: every claim generated by the caller (up to the LLM call that delegated) occurs verbatim
  in the brief. The brief carries the caller's output over whole, so its claims are already there;
* ``history``: the brief of the caller itself (its own input) occurs as a blob in this brief (see
  ``contains_blob``): the brief is the history so far, grown by one step, as in the trip planner.

The claims a brief could restate are its *source claims* (``source_claims``): the claims generated by
the caller, the delegation claims of the caller's own brief, and the claims generated by the other LLM
calls before the delegation (an orchestrator is handed the outputs of the specialists it called). They are
recorded as the ``input_claim`` relation of the receiving call, so that ``ClaimRelationExtractor``
relates the delegation claims to them like it does for the claims of an LLM call.
"""

from __future__ import annotations

import logging
import re
import uuid
from difflib import SequenceMatcher
from typing import NamedTuple

from symbolic_extractor.extractors.base import ElementExtractor, ExtractionPrompt
from symbolic_extractor.extractors.claims import _clip, _first_text, is_verbatim
from symbolic_extractor.extractors.tasks import _MARKER_RE, assignment_text, output_text
from symbolic_extractor.llm import LLMClient
from symbolic_extractor.models import Claim, ClaimItem, DelegationClaim, KGNode, SessionTrajectory
from symbolic_extractor.store import SymbolicSessionStore
from symbolic_extractor.usage import LLMUsage

logger = logging.getLogger(__name__)

#: Output of an agent call that hands the work over to another agent.
_DELEGATION_RE = re.compile(r"^(?:delegate|transfer|handoff)_to_\w+", re.IGNORECASE)
#: A speaker label and the quote opening a turn (``Finance: "``), as the model copies them from a transcript.
_SPEAKER_RE = re.compile(r"^\s*[^\n\":]{1,40}:\s*[\"\u201c]?")

#: A brief of the caller shorter than this (in words) proves nothing when found in another brief.
HISTORY_MIN_WORDS = 20
#: Share of the words of the caller's brief that must be found as one run in this brief. Not 1.0:
#: a history wrapped in JSON changes a few words around it (``"next": "x"``) from one call to the next.
HISTORY_MIN_COVER = 0.9
#: At most this many source claims are given to the relation extractor (the most recent ones): the
#: prompt lists them all, and the pairs to judge grow with their number.
MAX_SOURCE_CLAIMS = 40

SYSTEM_PROMPT = """\
You extract CLAIMS from the brief that one agent (the caller) wrote to another agent (the receiver) \
when it delegated work to it, in a multi-agent system trajectory.

A claim is a proposition, or a statement of stance, that the caller makes in the brief. You record \
what the caller says, NOT whether it is true. Typically the brief restates what the caller knows or \
has decided ("the root cause is the v2.18.3 deployment", "all upstream services are healthy"), or \
what it intends to do.

For each claim return:
- claim_text: the claim as one short, self-contained sentence. Stay faithful to the caller's wording \
and meaning, but resolve pronouns and references so the claim can be understood on its own. Do not \
add information the brief does not contain.
- claim_force: the act the caller performs.
    * "assertive": states something about the world, the situation or its own work.
    * "committing": states an action or choice the caller intends or adopts.
    * "directive": advises or instructs the receiver on something other than the work it is asked to do.
- claim_kind: the sort of content (what decides how the claim is verified later).
    * "factual": a source could confirm or refute it.
    * "evaluative": a judgment with no checkable core.
    * "recommendation": advises what to do, or what suits whom or when.
  Required when claim_force is "assertive". For "directive", set it only for advisory directives \
(recommendation) and use null for plain instructions. Always null for "committing".
- verbatim_source: the part of the BRIEF that expresses the claim, copied exactly, character for \
character: the FULL sentence (or list item) that contains the claim. Never a fragment, and do NOT \
paraphrase, shorten with "..." or change punctuation, capitalisation, markdown or numbers. The span \
must be contiguous and stay within one line or paragraph. Several claims may share the same excerpt.
  When the BRIEF quotes what other agents said (a transcript such as 'Finance: "No. I am holding 12%. \
Deal Desk is at 15%."'), copy only the sentence itself, as it stands inside the quoted turn: do NOT \
add the speaker label ('Finance:'), the quotation marks around the turn, or any text that is not \
next to the sentence in the BRIEF. Never join pieces that are not adjacent.

Rules:
- The work the receiver is asked to do (what to analyse, check, assess, provide) is its TASK, not a \
claim: never extract it. Extract only what the caller states or decides about the situation.
- A brief that only gives instructions, or only restates the user request, has no claim: return an \
empty list.
- One claim per proposition. Split compound sentences; never repeat a claim.
- Skip greetings, filler and questions.

Reply with a JSON object only:
{"claims": [{"claim_text": "...", "claim_force": "assertive|committing|directive", \
"claim_kind": "factual|evaluative|recommendation|null", "verbatim_source": "..."}]}
"""


class Caller(NamedTuple):
    """The agent that delegated, and the LLM call where it did."""

    llm_call: str  # id of the LLM call of the caller that delegated
    agent_call: str  # id of the AgentCall that owns it
    agent: str  # name of the caller agent


def is_delegation_output(raw: str | None) -> bool:
    """True when the output of an agent call is a delegation command (``delegate_to_<agent>``)."""
    return bool(_DELEGATION_RE.match(output_text(raw or "")))


def brief_text(node: KGNode) -> str | None:
    """The brief an AgentCall received, without the technical wrapping; None when the input carries
    none: it is empty or a bare resume marker. Whether it is really a brief of the caller, and not
    its history handed over, is decided on the content by ``skip_reason``."""
    raw = _first_text(node.node, "inputContent", "prompt")
    text = assignment_text(raw)
    if not text or _MARKER_RE.match(text):
        return None
    return text


def _words(text: str) -> list[str]:
    return re.findall(r"\w+", text.casefold())


def without_speaker(snippet: str, brief: str) -> str | None:
    """``snippet`` without the speaker label and the quotation marks a model adds when the brief is a
    transcript (``Finance: "Deal Desk is at 15%."`` for a sentence inside a longer turn), when what is
    left occurs in ``brief``; None otherwise. Only text is removed, and the result is checked like
    any quote, so nothing that is not in the brief can be accepted."""
    match = _SPEAKER_RE.match(snippet)
    if match is None:
        return None
    rest = snippet[match.end() :].rstrip().rstrip('"\u201d').strip()
    return rest if rest and is_verbatim(rest, brief) else None


def contains_blob(earlier: str, brief: str) -> bool:
    """True when ``earlier`` appears in ``brief`` as one block: the brief is that text plus more.

    Compared on words (case and punctuation ignored), so the wrapping around a text that changes
    from one call to the next (JSON keys, separators) does not hide it. ``earlier`` must be at least
    ``HISTORY_MIN_WORDS`` long, and the longest run of its words found in ``brief`` must cover
    ``HISTORY_MIN_COVER`` of them."""
    a, b = _words(earlier), _words(brief)
    if len(a) < HISTORY_MIN_WORDS or len(b) < len(a) * HISTORY_MIN_COVER:
        return False
    match = SequenceMatcher(None, a, b, autojunk=False).find_longest_match(0, len(a), 0, len(b))
    return match.size / len(a) >= HISTORY_MIN_COVER


def find_caller(trajectory: SessionTrajectory, call_id: str) -> Caller | None:
    """The caller of the AgentCall ``call_id``: the LLM call that delegated to it, see the module
    docstring. None when the call is unknown or no delegating LLM call ended before it started
    (the first call of a session, whose input is the user request)."""
    receiver = trajectory.step_for(call_id)
    if receiver is None:
        return None
    start = receiver.get("start_time") or 0.0
    delegating = {
        s["call_id"]: s
        for s in trajectory.steps
        if s.get("kind") == "agent" and s.get("call_id") != call_id and is_delegation_output(s.get("output_text"))
    }
    best: tuple[float, dict] | None = None
    for step in trajectory.steps:
        if step.get("kind") != "llm" or step.get("parent_id") not in delegating:
            continue
        end = (step.get("start_time") or 0.0) + (step.get("duration_ms") or 0.0) / 1000.0
        if end <= start and (best is None or end > best[0]):
            best = (end, step)
    if best is None:
        return None
    step = best[1]
    owner = delegating[step["parent_id"]]
    return Caller(step["call_id"], owner["call_id"], owner.get("agent_id") or "")


def _llm_steps_until(trajectory: SessionTrajectory, until: float, call_ids: set[str] | None = None) -> list[dict]:
    """LLM steps that started no later than ``until`` (only those owned by the agent calls
    ``call_ids`` when given), oldest first."""
    return sorted(
        (
            s
            for s in trajectory.steps
            if s.get("kind") == "llm"
            and (call_ids is None or s.get("parent_id") in call_ids)
            and (s.get("start_time") or 0.0) <= until
        ),
        key=lambda s: s.get("start_time") or 0.0,
    )


def _delegation_start(trajectory: SessionTrajectory, caller: Caller) -> float:
    step = trajectory.step_for(caller.llm_call)
    return (step.get("start_time") or 0.0) if step else 0.0


def caller_claims(store: SymbolicSessionStore, trajectory: SessionTrajectory, caller: Caller) -> list[Claim]:
    """The claims generated by the caller, up to the LLM call where it delegated."""
    until = _delegation_start(trajectory, caller)
    return [
        c.element
        for step in _llm_steps_until(trajectory, until, {caller.agent_call})
        for c in store.claims_for_node(step["call_id"])
    ]


def source_claims(store: SymbolicSessionStore, trajectory: SessionTrajectory, caller: Caller) -> list[Claim]:
    """The claims a brief of ``caller`` could restate, oldest first, at most ``MAX_SOURCE_CLAIMS``:

    * always: the delegation claims of the brief the caller itself received (A->B when looking at
      B->C), then the claims the caller generated up to its delegation;
    * to fill the rest: the claims generated by any other LLM call before the delegation, the most
      recent first. The relations between agent calls are not used to pick them: they do not always
      record that a worker's output went back to the caller (in the SRE session only telemetry is
      linked to the resumed ``sre``, though backend and db answered it too).
    """
    until = _delegation_start(trajectory, caller)
    own = caller_claims(store, trajectory, caller)
    brief = [c.element for c in store.for_node(caller.agent_call, "delegation_claims")]
    first = {c.id for c in [*brief, *own]}
    others = [
        c.element
        for step in _llm_steps_until(trajectory, until)
        for c in store.claims_for_node(step["call_id"])
        if c.id not in first
    ]
    room = max(MAX_SOURCE_CLAIMS - len(first), 0)
    chosen = [*(others[-room:] if room else []), *brief, *own]
    return list({c.id: c for c in chosen}.values())[-MAX_SOURCE_CLAIMS:]


def delegated_reply(trajectory: SessionTrajectory, call_id: str) -> tuple[Caller, str] | None:
    """The caller and the reply of the AgentCall ``call_id`` when it answers a delegation: its output
    (without the ``output:<agent>:`` prefix) is what the caller gets back. None when the call is not
    delegated to (no caller, see ``find_caller``), is a resumed call of the caller's own agent, has no
    output, or its output is itself a delegation command (it hands the work on, it does not answer)."""
    step = trajectory.step_for(call_id)
    if step is None or step.get("kind") != "agent":
        return None
    caller = find_caller(trajectory, call_id)
    if caller is None or caller.agent == step.get("agent_id"):
        return None
    raw = step.get("output_text") or ""
    reply = output_text(raw)
    if not reply or is_delegation_output(raw):
        return None
    return caller, reply


def reply_claims(store: SymbolicSessionStore, trajectory: SessionTrajectory, call_id: str, reply: str) -> list[Claim]:
    """The claims of the LLM calls of the AgentCall ``call_id`` whose ``verbatim_source`` occurs in its
    reply: they are what travels back to the caller, the others stay in the agent call. A claim
    with no ``verbatim_source``, or whose quote is past the point where the KG cut the output, is not
    recognised and counts as staying."""
    return [
        c.element
        for step in trajectory.steps
        if step.get("kind") == "llm" and step.get("parent_id") == call_id
        for c in store.claims_for_node(step["call_id"])
        if c.element.verbatim_source and is_verbatim(c.element.verbatim_source, reply)
    ]


def reply_receiver(
    store: SymbolicSessionStore, trajectory: SessionTrajectory, call_id: str, caller: Caller
) -> str | None:
    """The LLM call of the caller that reads the reply of the AgentCall ``call_id``: the first LLM call
    of the caller's agent that started after the agent call ended and generated claims (a call with no
    claim has nothing to relate). Later calls of the caller see the reply through the history, which
    is not recorded. None when there is none."""
    step = trajectory.step_for(call_id)
    if step is None:
        return None
    end = (step.get("start_time") or 0.0) + (step.get("duration_ms") or 0.0) / 1000.0
    for llm in trajectory.steps:
        if llm.get("kind") == "llm" and llm.get("parent_id") == call_id:
            end = max(end, (llm.get("start_time") or 0.0) + (llm.get("duration_ms") or 0.0) / 1000.0)
    later = sorted(
        (
            s
            for s in trajectory.steps
            if s.get("kind") == "llm" and s.get("agent_id") == caller.agent and (s.get("start_time") or 0.0) >= end
        ),
        key=lambda s: s.get("start_time") or 0.0,
    )
    return next((s["call_id"] for s in later if store.claims_for_node(s["call_id"])), None)


def skip_reason(
    brief: str, caller: Caller, store: SymbolicSessionStore | None, trajectory: SessionTrajectory
) -> str | None:
    """Why the brief has nothing new to extract (None: extract). See the module docstring.

    * ``relay``: the caller generated claims, and each one occurs verbatim in the brief;
    * ``history``: the input of the caller itself occurs as a blob in the brief."""
    if store is not None:
        claims = caller_claims(store, trajectory, caller)
        if claims and all(c.verbatim_source and is_verbatim(c.verbatim_source, brief) for c in claims):
            return "relay"
    step = trajectory.step_for(caller.agent_call)
    own = assignment_text((step or {}).get("input_text") or "")
    if own and contains_blob(own, brief):
        return "history"
    return None


class DelegationClaimPrompt(ExtractionPrompt[ClaimItem, DelegationClaim]):
    """The claims of one brief, for a known caller. The prompt is made per receiving call, because
    it carries the caller that ``find_caller`` found."""

    element_key = "delegation_claims"
    node_types = frozenset({"AgentCall"})
    item_model = ClaimItem
    system_prompt = SYSTEM_PROMPT
    reply_key = "claims"

    def __init__(self, caller: Caller) -> None:
        self._caller = caller

    def render(self, node: KGNode) -> str | None:
        brief = brief_text(node)
        if brief is None or not node.node_id:
            return None
        return (
            f"Caller agent: {self._caller.agent or 'unknown'}\n"
            f"Receiving agent: {_first_text(node.node, 'agentName', 'name') or 'unknown'}\n\n"
            f"=== BRIEF OF THE CALLER (extract claims from this) ===\n{_clip(brief)}\n"
        )

    def build_element(self, item: ClaimItem, node: KGNode) -> DelegationClaim:
        # Deterministic id: re-running on the same session yields the same ids.
        claim_id = str(
            uuid.uuid5(uuid.NAMESPACE_OID, f"{node.node_id}|delegation|{item.claim_force}|{item.claim_text}")
        )
        data = item.model_dump()
        snippet = data["verbatim_source"]
        if snippet is not None:
            brief = brief_text(node) or ""
            repaired = snippet if is_verbatim(snippet, brief) else without_speaker(snippet, brief)
            if repaired is not None:
                data["verbatim_source"] = repaired.strip()
            else:
                logger.warning(
                    "verbatim_source not found in the brief of AgentCall %s, dropping it: %r",
                    node.node_id,
                    snippet[:120],
                )
                data["verbatim_source"] = None
        return DelegationClaim(
            **data,
            id=claim_id,
            generated_by=self._caller.llm_call,
            caller_agent=self._caller.agent or "unknown",
            caller_call=self._caller.agent_call,
            delegated_to=node.node_id or "",
        )


class DelegationClaimExtractor:
    """The claims of the brief an AgentCall received from the agent that delegated to it.

    Same interface as ``ElementExtractor``; it needs the trajectory to find the caller, so it sets
    ``uses_trajectory`` and does nothing without one. A call with no brief, or whose caller is not
    found, costs no LLM request."""

    element_key = DelegationClaimPrompt.element_key
    node_types = DelegationClaimPrompt.node_types
    uses_trajectory = True

    def __init__(self, llm: LLMClient) -> None:
        self._llm = llm
        #: Usage of the last ``extract`` call (zero when no request was made).
        self.last_usage = LLMUsage()
        #: Cumulative usage of this extractor.
        self.usage = LLMUsage()

    def applies_to(self, node: KGNode) -> bool:
        return node.node_type in self.node_types

    def extract(
        self,
        node: KGNode,
        store: SymbolicSessionStore | None = None,
        *,
        trajectory: SessionTrajectory | None = None,
    ) -> list[DelegationClaim]:
        self.last_usage = LLMUsage()
        brief = brief_text(node) if trajectory is not None and node.node_id else None
        if brief is None or trajectory is None:
            return []
        caller = find_caller(trajectory, node.node_id or "")
        if caller is None:
            return []
        reason = skip_reason(brief, caller, store, trajectory)
        if reason is not None:
            logger.info("Delegation brief of %s not read (%s)", node.node_id, reason)
            return []
        inner = ElementExtractor(self._llm, DelegationClaimPrompt(caller))
        claims = inner.extract(node, store)
        self.last_usage = inner.last_usage
        self.usage = self.usage + inner.last_usage
        return claims
