"""Where the arguments of a tool call come from: ``supported_by`` (Fact -> Claim).

An agent calls ``calculate("3 + 2")``: the 3 and the 2 mean something (two travel times it has just stated),
but the tool call only holds the text. ``ArgumentOriginExtractor`` asks an LLM, for each tool call that has
arguments, which of the claims the agent made *so far in the same agent call* account for the value of each
argument, and records one ``supported_by`` link for each claim named.

The candidates are the claims generated by the LLM calls of the agent call that started before the tool call
(the one that requested it included), and the claims of the brief the agent call received when it was
delegated (delegation claims). Claims of other agent calls are not candidates: what an agent uses has to be
in its own context. The tool result is not shown to the model (the arguments come before it).

For each argument the model answers with a basis:

* ``stated``: the value is in a claim, as it stands (maybe reformatted);
* ``derived``: the value is built from what the claims state (computed, assembled, converted, picked among
  stated options): ``3 + 2`` from two stated travel times;
* ``none``: no claim accounts for it (it may come from the user request, a tool result, a default or the
  agent's own choice). Nothing is linked.

The link goes from the Fact of the tool call (its result, ``grounded_in`` the ToolCall) to each claim named:
the result is ``supported_by`` the claims its arguments come from, the same relation as between a claim and
the fact that backs it (opposite direction). Its attributes hold ``arguments`` (argument name -> basis). It is a judgement of an LLM from the texts, not a
fact of the trace: a "derived" link says the claims are the most plausible origin of the value.

One request per tool call. A tool call with no argument, or with no candidate claim, is not submitted. The
tool call is found through the ``Fact`` of its output (it carries ``tool_name``, ``tool_arguments`` and
``grounded_in``), so a tool call without output has none. See ``SymbolicExtractor._judge_tool_arguments``.
"""

from __future__ import annotations

import json
import logging
from collections.abc import Sequence
from typing import Any, Literal

from pydantic import BaseModel

from symbolic_extractor.llm import LLMClient, usage_of
from symbolic_extractor.models import Claim, Fact, SessionTrajectory, SymbolicStateElement
from symbolic_extractor.relations.fact_claim_links import SUPPORTED_BY
from symbolic_extractor.relations.semantic_relations import SemanticRelationExtractor
from symbolic_extractor.store import ANNOUNCES, SymbolicSessionStore
from symbolic_extractor.tool_calls import _time
from symbolic_extractor.usage import LLMUsage

logger = logging.getLogger(__name__)

#: At most this many candidate claims are shown (the most recent ones): the prompt lists them all.
MAX_CANDIDATES = 40
#: An argument value longer than this (in characters) is cut in the prompt.
MAX_VALUE_CHARS = 500

Basis = Literal["stated", "derived", "none"]

SYSTEM_PROMPT = """\
An agent of a multi-agent system is calling a tool. You are given the TOOL and its ARGUMENTS, and numbered \
CLAIMS (C1, C2, ...): what the agent has said so far, oldest first (some come from the brief the agent was \
given when it was handed the work). For each argument, say which claims its value comes from.

For each argument, answer with a basis:
- "stated": the value is in a claim, as it stands (maybe written differently: "3 hours" for 3).
- "derived": the value is built from what the claims state: computed, assembled, converted, or picked among \
stated options. For example 3 + 2 when the claims state a 3 hour leg and a 2 hour leg.
- "none": no claim accounts for the value. It may come from elsewhere (the user request, a tool result, a \
default) or be the agent's own choice. Do not guess: when you cannot trace the value to the claims, answer \
"none".

Rules:
- "from" lists the labels of ALL the claims the value is traced to (a value made of two figures can need \
two claims). It is empty exactly when the basis is "none".
- A claim that only shares the topic with the argument does not account for it: the value, or the parts it \
is built from, must be in the claim.
- A claim says what the agent claimed, not whether it is true: do not judge it.
- A claim marked [announces this call] is what the agent said before making the call: it can be the origin \
of a value, but only when it contains it.
- Judge only from the texts. Do not use outside knowledge.
- Answer for every argument, once. "name" is the name of the argument only (for the line `- expression = "3 + 2"` \
it is `expression`), not its value.

Reply with a JSON object only:
{"arguments": [{"name": "<argument>", "basis": "stated|derived|none", "from": ["C1"], "reasoning": "one sentence"}]}"""


def retry_reminder() -> str:
    """Added to the request that retries a reply that was not usable."""
    return (
        '\n\nYour previous reply was not valid. Reply with a JSON object with the key "arguments", a list with '
        'one item per argument: {"name": ..., "basis": "stated|derived|none", "from": [labels], "reasoning": ...}.'
    )


class ArgumentOrigin(BaseModel):
    """What the model said about one argument of a tool call."""

    argument: str
    value: Any = None
    basis: Basis = "none"
    #: Ids of the claims the value is traced to (``[]`` when the basis is ``none``).
    claim_ids: list[str] = []
    reasoning: str = ""


class ArgumentOriginEvaluation(BaseModel):
    """The verdict on one tool call: where each of its arguments comes from."""

    #: Id of the ToolCall node, and of the Fact of its output (the element the call was found through).
    tool_call_id: str
    fact_id: str
    tool_name: str | None = None
    #: Ids of the claims the arguments were compared with (all the candidates shown).
    candidate_ids: list[str]
    origins: list[ArgumentOrigin]

    @property
    def traced(self) -> list[ArgumentOrigin]:
        """The arguments traced to at least one claim."""
        return [o for o in self.origins if o.claim_ids]


def candidate_claims(
    store: SymbolicSessionStore,
    trajectory: SessionTrajectory,
    tool_call_id: str,
    limit: int = MAX_CANDIDATES,
) -> list[Claim]:
    """The claims the agent had made when it called tool ``tool_call_id``: the delegation claims of the brief
    of its agent call, then the claims of the LLM calls of that agent call that started before the tool call
    (the LLM call that requested it included), in order. At most the ``limit`` most recent. ``[]`` when the
    tool call or its agent call is not in the trajectory."""
    step = trajectory.step_for(tool_call_id)
    if step is None or step.get("kind") != "tool" or not step.get("parent_id"):
        return []
    parent, start = step["parent_id"], _time(step)
    llm_calls = sorted(
        (s for s in trajectory.steps if s.get("kind") == "llm" and s.get("parent_id") == parent and _time(s) <= start),
        key=_time,
    )
    claims = [s.element for s in store.for_node(parent, "delegation_claims")]
    for llm in llm_calls:
        claims.extend(s.element for s in store.claims_for_node(llm["call_id"]))
    return claims[-limit:]


def _show(value: Any) -> str:
    text = json.dumps(value, ensure_ascii=False, default=str)
    return text if len(text) <= MAX_VALUE_CHARS else text[:MAX_VALUE_CHARS] + "..."


def render_prompt(
    fact: Fact, claims: Sequence[Claim], announcing: set[str] = frozenset(), brief: set[str] = frozenset()
) -> str:
    """The request: the tool, its arguments and the numbered claims. ``announcing`` are the ids of the claims
    that announce this call, ``brief`` those of the delegation claims (marked as such). The tool output is not
    in it."""
    arguments = "\n".join(f"- {name} = {_show(value)}" for name, value in fact.tool_arguments.items())
    lines = []
    for i, claim in enumerate(claims, start=1):
        marks = ""
        if claim.id in brief:
            marks += " [from the brief the agent received]"
        if claim.id in announcing:
            marks += " [announces this call]"
        lines.append(f"C{i}. {claim.claim_text}{marks}")
    return f"=== TOOL ===\n{fact.tool_name or 'unknown'}\n\n=== ARGUMENTS ===\n{arguments}\n\n=== CLAIMS ===\n" + "\n".join(lines) + "\n"


def _argument_named(raw: Any, fact: Fact) -> str | None:
    """The argument of ``fact`` a reply item is about. The model is asked for the name, but may give the line
    of the prompt it read it from (``expression = "3 + 2"``): the name is then what comes before the ``=``."""
    text = str(raw or "").strip()
    if text in fact.tool_arguments:
        return text
    head = text.split("=", 1)[0].strip().lstrip("-").strip()
    return head if head in fact.tool_arguments else None


def parse_origins(data: dict, fact: Fact, claims: Sequence[Claim]) -> list[ArgumentOrigin]:
    """One ``ArgumentOrigin`` per argument of ``fact``, from the reply. A name that is not an argument is
    ignored (logged), a label that is not a claim is ignored, an argument the reply does not mention (or whose
    basis is not stated/derived, or whose labels are all unknown) is ``none``. Raises ``ValueError`` when the
    reply has no list under ``arguments``: that is a failed request, not "nothing comes from the claims"."""
    items = data.get("arguments")
    if not isinstance(items, list):
        raise ValueError(f"no 'arguments' list in the reply: {str(data)[:200]}")
    by_label = {f"C{i}": c for i, c in enumerate(claims, start=1)}
    said: dict[str, dict] = {}
    for item in items:
        name = _argument_named(item.get("name"), fact) if isinstance(item, dict) else None
        if name is not None:
            said.setdefault(name, item)
        else:
            logger.warning("Argument %r of the reply is not an argument of the tool call, ignored", item)
    origins = []
    for name, value in fact.tool_arguments.items():
        item = said.get(name, {})
        basis = str(item.get("basis") or "none").strip().lower()
        labels = item.get("from")
        found: list[str] = []
        for raw in labels if isinstance(labels, list) else []:
            label = str(raw).strip().upper()
            claim = by_label.get(f"C{label}" if label.isdigit() else label)
            if claim is None:
                logger.warning("Claim %r of the reply is not in the list, ignored", raw)
            elif claim.id not in found:
                found.append(claim.id)
        if basis not in ("stated", "derived") or not found:
            basis, found = "none", []
        origins.append(
            ArgumentOrigin(
                argument=name,
                value=value,
                basis=basis,
                claim_ids=found,
                reasoning=str(item.get("reasoning") or "").strip(),
            )
        )
    return origins


class ArgumentOriginExtractor(SemanticRelationExtractor):
    """Judges where the arguments of a tool call come from, see the module docstring.

    ``extract(store, elements, trajectory)`` handles the ``Fact`` elements of ``elements`` that have
    ``tool_arguments`` (others are ignored). It returns one ``ArgumentOriginEvaluation`` per tool call judged
    and records ``supported_by`` (fact of the tool call -> claim, attribute ``arguments``: argument name ->
    basis) in the store for each claim named. Without a
    ``trajectory`` the agent call of the tool call is unknown and nothing is judged.
    """

    def __init__(self, llm: LLMClient) -> None:
        super().__init__()
        self._llm = llm

    def extract(  # type: ignore[override]
        self,
        store: SymbolicSessionStore,
        elements: Sequence[SymbolicStateElement],
        trajectory: SessionTrajectory | None = None,
    ) -> list[ArgumentOriginEvaluation]:
        """The evaluations, with the ``supported_by`` relations also recorded in ``store``. ``last_usage`` is
        the total usage. Facts with no argument, or whose tool call has no candidate claim (yet), are
        skipped. Raises ``ValueError`` when a reply is unusable twice (the evaluations already done are kept
        in the store)."""
        self.last_usage = LLMUsage()
        evaluations: list[ArgumentOriginEvaluation] = []
        if trajectory is None:
            return evaluations
        for element in elements:
            if not isinstance(element, Fact) or not element.tool_arguments or store.get(element.id) is None:
                continue
            claims = candidate_claims(store, trajectory, element.grounded_in)
            if not claims:
                continue
            evaluation = self.evaluate(store, element, claims)
            by_claim: dict[str, dict[str, str]] = {}
            for origin in evaluation.origins:
                for claim_id in origin.claim_ids:
                    by_claim.setdefault(claim_id, {})[origin.argument] = origin.basis
            for claim_id, arguments in by_claim.items():
                store.link(SUPPORTED_BY, element.id, claim_id, arguments=arguments)
            evaluations.append(evaluation)
        return evaluations

    def has_candidates(self, store: SymbolicSessionStore, trajectory: SessionTrajectory, fact: Fact) -> bool:
        """Whether ``fact`` is ready to be judged: it has arguments and its tool call has candidate claims."""
        return bool(fact.tool_arguments) and bool(candidate_claims(store, trajectory, fact.grounded_in, limit=1))

    def evaluate(self, store: SymbolicSessionStore, fact: Fact, claims: Sequence[Claim]) -> ArgumentOriginEvaluation:
        """Where the arguments of ``fact`` come from, among ``claims``: one request, and one more when the reply
        is not usable (not JSON at all, the client raises ``ValueError``, or JSON that ``parse_origins``
        rejects). The usage of every request that returned is added to ``last_usage``. API errors are not
        caught. Raises ``ValueError`` when the second reply is unusable too."""
        announcing = set(store.related_from(ANNOUNCES, fact.grounded_in))
        brief = {s.id for s in store.by_kind("delegation_claims")}
        prompt = render_prompt(fact, claims, announcing, brief)
        for attempt in (1, 2):
            try:
                reply = self._llm.complete_json(SYSTEM_PROMPT, prompt if attempt == 1 else prompt + retry_reminder())
            except ValueError as exc:
                self.last_usage = self.last_usage + usage_of(exc)
                if attempt == 2:
                    raise
                logger.warning("Reply is not valid JSON, asking again: %.200s", exc)
                continue
            self.last_usage = self.last_usage + reply.usage
            try:
                origins = parse_origins(reply.data, fact, claims)
            except ValueError:
                if attempt == 2:
                    raise
                logger.warning("Unusable reply, asking again: %.200s", str(reply.data))
                continue
            return ArgumentOriginEvaluation(
                tool_call_id=fact.grounded_in,
                fact_id=fact.id,
                tool_name=fact.tool_name,
                candidate_ids=[c.id for c in claims],
                origins=origins,
            )
        raise AssertionError("unreachable")
