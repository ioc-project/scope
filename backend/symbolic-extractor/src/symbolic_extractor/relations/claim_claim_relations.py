"""Relations between the claims an LLM call generated, and with the claims in its input.

``ClaimRelationExtractor`` takes the set of claims C generated by an LLM call and relates each
claim of C to the claims that were in the input of that call (``input_claim`` relation of the
store) and to the other claims of C. One LLM request per call lists the relations it finds:

    conflict      the two cannot both be true (or both be followed): direct (different values for the
                  same thing) or indirect (incompatible once the consequences are worked out)
    same          the two state the same thing in other words
    derived_from  the new claim was built on the other one (it follows from it, applies it, or
                  decides because of it). A new claim can derive from an input claim, never the
                  other way round, since it exists before. Between two new claims either can
                  derive from the other, so the direction is given by the reply. The prompt
                  still calls it "contributes" (the reply label); it is mapped to ``derived_from``

Every other pair has no relation. The reply is JSON; only the pairs with a relation are listed.
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from typing import Literal

from pydantic import BaseModel

from symbolic_extractor.llm import LLMClient, usage_of
from symbolic_extractor.models import Claim, SymbolicStateElement
from symbolic_extractor.relations.semantic_relations import SemanticRelationExtractor
from symbolic_extractor.store import SymbolicSessionStore
from symbolic_extractor.usage import LLMUsage

logger = logging.getLogger(__name__)

#: Store relations recorded by ``ClaimRelationExtractor.extract``. ``conflicts_with`` and ``same_as``
#: are symmetric (recorded in both directions); ``derived_from`` goes from the claim built on
#: another one (a new claim) to the claim it is built on (an input claim, or another new claim).
#: ``same_as`` is the LLM-judged counterpart of ``same_claim``, which is the one computed from
#: embeddings.
CONFLICTS_WITH = "conflicts_with"
SAME_AS = "same_as"
DERIVED_FROM = "derived_from"

RelationKind = Literal["conflict", "same", "derived_from"]

#: Spellings accepted in the reply -> relation kind. The prompt asks for "contributes".
_KINDS: dict[str, RelationKind] = {
    "conflict": "conflict",
    "conflicts": "conflict",
    "same": "same",
    "same_claim": "same",
    "contributes": "derived_from",
    "contributes_to": "derived_from",
    "derived_from": "derived_from",
}

SYSTEM_PROMPT = """\
You are given two lists of claims made by AI agents. The NEW claims (N1, N2, ...) were just \
generated by an agent in one LLM call. The EARLIER claims (E1, E2, ...) were in the input of that \
same call: they come from earlier steps of the agent or from other agents (the list can be empty). \
Find the relations between a new claim and an earlier claim, and between two new claims. A pair \
has at most one relation:

- conflict: the two claims cannot both be true, or cannot both be followed, at the same time. \
Either they give different or opposite values, facts or decisions about the SAME thing (the same \
quantity, item, event or choice), or nothing is opposite on its face but they are incompatible \
once their consequences are worked out (sums, totals, counts, durations, schedules, units). Do the \
calculation: if the numbers agree, there is no conflict.
- same: the two claims state the same thing in other words, units or rounding. Neither adds \
information that the other lacks. A new claim that only restates another claim is "same", not \
"contributes".
- contributes: the "other" claim is something the "new" claim was built on: the "new" claim follows \
from it (alone or together with other claims), applies it, or decides something because of it. A \
shared topic is not enough. An earlier claim can contribute to a new claim, never the other way \
round. Between two new claims, say which one is built on the other.

Report a relation only when you can show it from what the claims say; do not use outside \
knowledge. Most pairs have no relation: leave them out. A false alarm is worse than a missed \
doubtful case, above all for "conflict". These are NOT relations: the same subject with different \
details, claims about different aspects of the task, compatible claims that do not depend on each \
other.

Reply with a JSON object only, one entry per related pair, using the labels as given. "new" is a \
new claim; "other" is an earlier claim (E) or another new claim (N), never the same claim as "new". \
For "contributes", "other" is the claim that contributes and "new" the claim built on it. For \
"conflict" and "same" the order does not matter, and a pair is listed once:
{"relations": [{"new": "N2", "other": "E5", "relation": "contributes", \
"reasoning": "one sentence"}]}
"relation" is one of "conflict", "same", "contributes". Reply {"relations": []} when there is none.
The only top-level key is "relations". Do not comment on, summarise or restate the claims, and do \
not answer with anything else, even when the claims are unclear."""

#: Added to the request that retries a reply that had no usable ``relations`` list.
RETRY_REMINDER = (
    '\n\nYour previous reply was not valid. Reply with a JSON object with a single key "relations" '
    'whose value is a list ([] when no pair is related), for example {"relations": []}.'
)


class ClaimRelation(BaseModel):
    """A relation between a claim generated by an LLM call and another claim: one of the claims in
    the input of that call, or another claim generated by the same call."""

    #: The new claim (generated by the LLM call). For ``derived_from`` it is the claim built on
    #: ``other_id``.
    claim_id: str
    #: The other claim: an earlier claim (in the input of that call) or another new claim.
    other_id: str
    relation: RelationKind
    reasoning: str = ""


def render_prompt(new_claims: Sequence[Claim], earlier_claims: Sequence[Claim]) -> str:
    new = "\n".join(f"N{i}. {c.claim_text}" for i, c in enumerate(new_claims, start=1))
    earlier = "\n".join(f"E{i}. {c.claim_text}" for i, c in enumerate(earlier_claims, start=1))
    return f"=== NEW CLAIMS ===\n{new}\n\n=== EARLIER CLAIMS ===\n{earlier or '(none)'}\n"


def _label(value: object) -> str:
    return str(value).strip().upper()


def parse_relations(
    data: dict, new_claims: Sequence[Claim], earlier_claims: Sequence[Claim]
) -> list[ClaimRelation]:
    """The relations of a reply. Entries with an unknown label or relation, or relating a claim to
    itself, are ignored (logged). A pair given twice with the same relation counts once (for
    ``conflict`` and ``same`` in either order), and a pair given with different relations is
    dropped (it is not known which one is meant), also two ``derived_from`` in opposite directions.
    Raises ``ValueError`` when the reply has no list of relations at all, which is a failed
    request, not "no relation"."""
    entries = data.get("relations")
    if not isinstance(entries, list):
        raise ValueError(f"no 'relations' list in the reply: {str(data)[:200]}")
    new_by_label = {f"N{i}": c for i, c in enumerate(new_claims, start=1)}
    earlier_by_label = {f"E{i}": c for i, c in enumerate(earlier_claims, start=1)}

    # by unordered pair of claims: relation (with the direction of a derived_from) -> relation
    found: dict[frozenset[str], dict[str, ClaimRelation]] = {}
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        new = new_by_label.get(_label(entry.get("new")))
        other_label = _label(entry.get("other", entry.get("earlier")))
        other = earlier_by_label.get(other_label) or new_by_label.get(other_label)
        kind = _KINDS.get(str(entry.get("relation", "")).strip().lower())
        if new is None or other is None or kind is None or other.id == new.id:
            logger.warning("Claim relation ignored: %s", str(entry)[:200])
            continue
        variant = f"derived_from:{other.id}" if kind == "derived_from" else kind
        relation = ClaimRelation(
            claim_id=new.id,
            other_id=other.id,
            relation=kind,
            reasoning=str(entry.get("reasoning", "")).strip(),
        )
        found.setdefault(frozenset((new.id, other.id)), {}).setdefault(variant, relation)

    relations = []
    for pair, variants in found.items():
        if len(variants) > 1:
            logger.warning(
                "Claims %s got several relations %s: dropped", sorted(pair), sorted(variants)
            )
            continue
        relations.extend(variants.values())
    return relations


class ClaimRelationExtractor(SemanticRelationExtractor):
    """Relations between the claims of an LLM call, and with the claims in its input.

    ``extract(store, elements)`` takes the claims of ``elements`` (the new claims, one group per
    LLM call: the node they are stored under) and, for each call, relates them to the claims
    recorded in the store as its input (``input_claim``) and to each other. It makes one request
    per call, none when the call has no input claims and only one new claim (there is no pair to
    judge), and records the relations in the store (see the constants ``CONFLICTS_WITH``,
    ``SAME_AS``, ``DERIVED_FROM``). The prompt lists every claim, so it grows with the number of
    claims, and the pairs to judge with its square.
    """

    def __init__(self, llm: LLMClient) -> None:
        super().__init__()
        self._llm = llm

    def extract(
        self, store: SymbolicSessionStore, elements: Sequence[SymbolicStateElement]
    ) -> list[ClaimRelation]:
        """The relations found, also recorded in ``store``. ``last_usage`` is the total usage.
        Claims that are not in the store are ignored. Raises ``ValueError`` when a reply has no
        list of relations (the relations of the calls already done are kept)."""
        self.last_usage = LLMUsage()
        by_node: dict[str, list[Claim]] = {}
        for element in elements:
            stored = store.get(element.id) if isinstance(element, Claim) else None
            if stored is not None:
                by_node.setdefault(stored.node_id, []).append(element)

        relations: list[ClaimRelation] = []
        for node_id, new_claims in by_node.items():
            new_ids = {c.id for c in new_claims}
            earlier_claims = [
                s.element
                for claim_id in store.related("input_claim", node_id)
                if (s := store.get(claim_id)) is not None
                and isinstance(s.element, Claim)
                and s.element.id not in new_ids
            ]
            if not earlier_claims and len(new_claims) < 2:
                continue
            found = self.relate(new_claims, earlier_claims)
            for relation in found:
                self._record(store, relation)
            relations.extend(found)
        return relations

    def relate(
        self, new_claims: Sequence[Claim], earlier_claims: Sequence[Claim]
    ) -> list[ClaimRelation]:
        """The relations between the new claims and the earlier ones, and among the new claims: one
        request, and one more when the reply is not usable: not JSON at all (the client raises
        ``ValueError``) or JSON without a ``relations`` list (the model sometimes answers with
        something else). The usage of every request that returned is added to ``last_usage``. API
        errors are not caught. Raises ``ValueError`` when the second reply is unusable too."""
        prompt = render_prompt(new_claims, earlier_claims)
        for attempt in (1, 2):
            try:
                reply = self._llm.complete_json(
                    SYSTEM_PROMPT, prompt if attempt == 1 else prompt + RETRY_REMINDER
                )
            except ValueError as exc:
                self.last_usage = self.last_usage + usage_of(exc)
                if attempt == 2:
                    raise
                logger.warning("Reply is not valid JSON, asking again: %.200s", exc)
                continue
            self.last_usage = self.last_usage + reply.usage
            try:
                return parse_relations(reply.data, new_claims, earlier_claims)
            except ValueError:
                if attempt == 2:
                    raise
                logger.warning(
                    "Reply without a relations list, asking again: %.200s", str(reply.data)
                )
        raise AssertionError("unreachable")

    @staticmethod
    def _record(store: SymbolicSessionStore, relation: ClaimRelation) -> None:
        new_id, other_id = relation.claim_id, relation.other_id
        if relation.relation == "derived_from":
            store.link(DERIVED_FROM, new_id, other_id)
            return
        name = CONFLICTS_WITH if relation.relation == "conflict" else SAME_AS
        store.link(name, new_id, other_id)
        store.link(name, other_id, new_id)
