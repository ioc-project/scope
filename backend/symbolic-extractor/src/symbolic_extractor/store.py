"""In-memory store of the symbolic state elements extracted from one session.

It holds every extracted element (Claim now; Goal, Task, ... later) together with the id of
the KG node it refers to (the LLMCall for a Claim), so later steps (linking, tracking a
claim across agents, writing to the KG) can query it without touching the KG or the files.
It is a working structure for computation; what is finally persisted is the KG.

Relations are labelled links between ids (``link`` / ``related``), each also kept as an ``Edge`` in the
order it was first recorded (``edges`` / ``edge_count`` / ``edges_since``), with optional attributes.
The relations: ``input_claim`` and ``input_fact`` (LLMCall -> Claim / Fact present in its input), ``in_context`` (Fact -> each Claim
generated by an LLMCall that had the fact in its input), ``same_claim`` (Claim -> input
Claim judged to be the same claim) and ``supported_by`` (Claim -> Fact that supports it, set by
``FactClaimLinker``). ``ClaimRelationExtractor`` adds ``conflicts_with`` and ``same_as`` (Claim <->
Claim, both directions) and ``derived_from`` (Claim -> the Claim it is built on: an input Claim, or another Claim of the same call).
``SymbolicExtractor._link_same_task`` adds ``same_as`` between identical Tasks (both directions).
``call_preceded_by`` (AgentCall -> the AgentCall control came from) is recorded with the input
tracking, together with ``call_returned_from`` (router AgentCall -> the worker call that handed
control back to it), and ``preceded_by`` (Task -> each Task of that preceding agent call) is derived
from them when the tasks are extracted: the raw order of the tasks, like ``in_context`` for claims and facts.
``TaskRelationExtractor`` adds ``implements`` (Task -> the Task it was preceded by, or the Goal,
that it carries out).
``SymbolicExtractor._link_answers`` adds ``answers`` (each Claim of the final answer -> the Goal).
``GoalClaimRelationExtractor`` adds ``fulfils`` (each Claim of the final answer that carries the
satisfaction of the Goal -> the Goal).
``SymbolicExtractor._link_produced_by`` adds ``produced_by`` (each Claim -> the Task(s) of the agent
call that owns the LLM call that generated it), and ``TaskClaimRelationExtractor`` adds
``fulfils_task`` (each Claim that fulfils the Task -> the Task).
``SymbolicExtractor._link_announces`` adds ``announces`` (each committing Claim -> the ToolCall node(s) it
announces, found through the tool call ids the claim extractor read in the output of its LLM call).
``SymbolicExtractor._link_system_tasks`` adds ``has_system_task`` (each AgentCall -> the SystemTasks of
its agent), and ``_link_capabilities`` ``has_capability`` (each AgentCall -> the Capabilities of its agent).
``CapabilityTaskRelationExtractor`` adds ``supports`` (each Capability that supports a Task or SystemTask of its
agent -> that task).
``SymbolicExtractor._link_replies`` adds ``reply_claim`` (each delegated AgentCall -> the Claims of its
LLM calls that occur in its reply) and records those claims as ``input_claim`` of the next LLM call of
the caller that generated claims.
``SymbolicExtractor._link_constraints`` adds ``bounded_by`` (each Goal -> the user Constraints of its
Conversation node, each Task -> the system Constraints of its agent).
Other relations between symbolic state
elements (derivedFrom between claims, ...) are not modelled yet.
"""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass
from itertools import islice
from typing import TYPE_CHECKING, Any

from pydantic import BaseModel, Field

if TYPE_CHECKING:
    # models imports symbolic_state, which imports this module: only needed for annotations
    from symbolic_extractor.models import SymbolicStateElement

#: Relation Fact -> Claim: the fact was in the input of the LLM call that generated the claim.
IN_CONTEXT = "in_context"
#: Relation AgentCall -> AgentCall: the agent call that handed the work over to it (a transition of
#: the trajectory, see ``symbolic_state.build_transitions``; a worker returning control to its
#: router is not one). Recorded with the input tracking, so it needs the trajectory.
CALL_PRECEDED_BY = "call_preceded_by"
#: Relation AgentCall -> AgentCall: the worker call that handed control back to this (router) call,
#: a ``return`` transition of the trajectory. Not a delegation, so it is not ``call_preceded_by``;
#: it is only followed to pass through a router call that has no task, see
#: ``SymbolicExtractor._closest_tasks``.
CALL_RETURNED_FROM = "call_returned_from"
#: Relation Task -> Task: the task is owned by an agent call that was preceded by the agent call
#: owning the other task: the closest agent call before it that has a task (calls without task are
#: passed over, up to the root). Raw order, no judgement; see
#: ``SymbolicExtractor._link_preceding_tasks``.
PRECEDED_BY = "preceded_by"
#: Relation Claim -> Goal (``mas:answers`` of the ontology): the claim was generated by the LLM call
#: that wrote the final answer of the session (see ``SessionTrajectory.final_llm_call``). Not a
#: judgement of whether the claim meets the goal: it is the set of claims that deliver the outcome.
#: Whether such a claim satisfies the goal is ``mas:fulfils`` (``GoalClaimRelationExtractor``).
ANSWERS = "answers"
#: Relation Claim -> Task (``mas:producedBy`` of the ontology): the claim was generated by an LLM call of
#: the agent call that owns the task. Raw provenance, no judgement; whether the claim fulfils the
#: task is ``mas:fulfils`` (``TaskClaimRelationExtractor``). See ``SymbolicExtractor._link_produced_by``.
PRODUCED_BY = "produced_by"
#: Relation Claim -> ToolCall node: the committing claim announces the tool call ("I will calculate the
#: total time" -> the ``calculate`` call that follows). Deterministic: the claim extractor names the ids of
#: the requests in the LLM output, the trajectory gives the ToolCall node that ran each. No ontology
#: property yet. See ``SymbolicExtractor._link_announces``.
ANNOUNCES = "announces"
#: Relation AgentCall -> SystemTask: the standing task of the agent (read from its system prompt, once
#: per agent) that the call carries. Every agent call of an agent has the same ones. Deterministic, see
#: ``SymbolicExtractor._link_system_tasks``.
HAS_SYSTEM_TASK = "has_system_task"
#: Relation AgentCall -> Capability: what the agent that made the call is able to do (read from its system
#: prompt, once per agent). Every agent call of an agent has the same ones. Deterministic, see
#: ``SymbolicExtractor._link_capabilities``.
HAS_CAPABILITY = "has_capability"
#: Relation AgentCall -> Claim: the claim, generated by an LLM call of that (delegated) agent call, occurs
#: in the reply the agent call gives back to its caller, i.e. it travels back; the other claims of the
#: agent call stay in it. See ``SymbolicExtractor._link_replies``.
REPLY_CLAIM = "reply_claim"
#: Relation Goal -> Constraint and Task -> Constraint (``mas:boundedBy`` of the ontology): the constraint bounds
#: the goal or the task. Deterministic, nothing is judged: a user constraint bounds the goals read from the
#: same Conversation node, a system constraint bounds the tasks of the agent calls of its agent. See
#: ``SymbolicExtractor._link_constraints``.
BOUNDED_BY = "bounded_by"


class Edge(BaseModel):
    """A relation between two ids of the store: ``source_id -[edge_type]-> target_id``. The ids are element
    ids, or ids of KG nodes (an AgentCall for ``has_capability``). Same field names as the ``KGEdge`` of the
    ontology models (``edge_type``, ``source_id``, ``target_id``). ``attributes`` holds what describes the
    edge itself and neither of its ends (empty when nothing does)."""

    edge_type: str
    source_id: str
    target_id: str
    attributes: dict[str, Any] = Field(default_factory=dict)


@dataclass(frozen=True)
class StoredElement:
    """A symbolic state element and the KG node it refers to."""

    kind: str  # element key, e.g. "claims"
    node_id: str  # id of the KG node the element is anchored to (LLMCall for a Claim)
    element: SymbolicStateElement  # e.g. ``Claim`` or ``Fact``

    @property
    def id(self) -> str:
        return self.element.id


class SymbolicSessionStore:
    """Symbolic state elements of one session, indexed by element id, KG node id and kind."""

    def __init__(self, session_id: str) -> None:
        self.session_id = session_id
        self._by_id: dict[str, StoredElement] = {}
        # dicts used as insertion-ordered sets of element ids
        self._by_node: dict[str, dict[str, None]] = {}
        self._by_kind: dict[str, dict[str, None]] = {}
        # relation name -> source id -> target ids (insertion-ordered set)
        self._relations: dict[str, dict[str, dict[str, None]]] = {}
        # (relation, source id, target id) -> edge, in the order the edges were first recorded
        self._edges: dict[tuple[str, str, str], Edge] = {}

    def add(self, kind: str, element: SymbolicStateElement, node_id: str | None) -> StoredElement:
        """Record ``element`` as referring to KG node ``node_id``.

        Adding an element whose id is already stored replaces it (re-running an extraction
        is idempotent, since element ids are deterministic).
        """
        element_id = getattr(element, "id", None)
        if not element_id:
            raise ValueError(f"A {kind} element needs an id to be stored")
        if not node_id:
            raise ValueError(f"{kind} element {element_id} needs the id of the node it refers to")

        previous = self._by_id.get(element_id)
        if previous is not None:
            self._by_node[previous.node_id].pop(element_id, None)
            self._by_kind[previous.kind].pop(element_id, None)

        stored = StoredElement(kind=kind, node_id=node_id, element=element)
        self._by_id[element_id] = stored
        self._by_node.setdefault(node_id, {})[element_id] = None
        self._by_kind.setdefault(kind, {})[element_id] = None
        return stored

    def get(self, element_id: str) -> StoredElement | None:
        return self._by_id.get(element_id)

    def for_node(self, node_id: str, kind: str | None = None) -> list[StoredElement]:
        """Elements referring to KG node ``node_id`` (optionally only of one ``kind``),
        in insertion order."""
        ids = self._by_node.get(node_id, {})
        found = (self._by_id[i] for i in ids)
        return [s for s in found if kind is None or s.kind == kind]

    def claims_for_node(self, node_id: str) -> list[StoredElement]:
        return self.for_node(node_id, "claims")

    def link(self, relation: str, source_id: str, target_id: str, **attributes: Any) -> bool:
        """Record ``source_id -[relation]-> target_id`` (idempotent). ``attributes`` describe the edge; linking
        an existing edge again updates them. Returns True when the edge is new, False when it was there."""
        key = (relation, source_id, target_id)
        edge = self._edges.get(key)
        if edge is not None:
            edge.attributes.update(attributes)
            return False
        self._edges[key] = Edge(
            edge_type=relation, source_id=source_id, target_id=target_id, attributes=dict(attributes)
        )
        self._relations.setdefault(relation, {}).setdefault(source_id, {})[target_id] = None
        return True

    def edges(self) -> list[Edge]:
        """Every edge, in the order it was first recorded."""
        return list(self._edges.values())

    def edge_count(self) -> int:
        """Number of edges so far: a marker for ``edges_since``."""
        return len(self._edges)

    def edges_since(self, count: int) -> list[Edge]:
        """The edges recorded after the store held ``count`` of them (``edge_count`` taken earlier): the new
        ones. An edge linked again later is not new, so it is not listed twice."""
        return list(islice(self._edges.values(), count, None))

    def related(self, relation: str, source_id: str) -> list[str]:
        """Target ids of ``relation`` from ``source_id``, in insertion order."""
        return list(self._relations.get(relation, {}).get(source_id, {}))

    def related_from(self, relation: str, target_id: str) -> list[str]:
        """Source ids that have ``relation`` to ``target_id`` (the inverse of ``related``), in insertion order."""
        return [source for source, targets in self._relations.get(relation, {}).items() if target_id in targets]

    def by_kind(self, kind: str) -> list[StoredElement]:
        return [self._by_id[i] for i in self._by_kind.get(kind, {})]

    def kinds(self) -> list[str]:
        return [kind for kind, ids in self._by_kind.items() if ids]

    def __iter__(self) -> Iterator[StoredElement]:
        return iter(self._by_id.values())

    def __len__(self) -> int:
        return len(self._by_id)

    def __contains__(self, element_id: object) -> bool:
        return element_id in self._by_id
