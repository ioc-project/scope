import pytest

from symbolic_extractor import SymbolicSessionStore
from symbolic_extractor.llm import LLMReply
from symbolic_extractor.models import Claim
from symbolic_extractor.relations import (
    CONFLICTS_WITH,
    DERIVED_FROM,
    SAME_AS,
    ClaimRelationExtractor,
)
from symbolic_extractor.relations.claim_claim_relations import parse_relations, render_prompt
from symbolic_extractor.usage import LLMUsage


class JsonLLM:
    """JSON LLM that answers the given replies in order and records the user messages. A reply
    that is an exception is raised instead (like the client does for a reply that is not JSON)."""

    def __init__(self, *replies):
        self.replies = list(replies)
        self.prompts = []

    def complete_json(self, system, user):
        self.prompts.append(user)
        reply = self.replies[len(self.prompts) - 1]
        if isinstance(reply, Exception):
            raise reply
        return LLMReply(data=reply, usage=LLMUsage(calls=1, prompt_tokens=100, completion_tokens=20, cost_usd=0.002))


def claim(text, cid):
    return Claim(id=cid, claim_text=text, claim_force="assertive", claim_kind="factual", verbatim_source=text)


def session():
    """Node l1 generated e1, e2; node l2 had both in its input and generated n1, n2."""
    store = SymbolicSessionStore("s1")
    e1, e2 = claim("The hotel costs $100 a night.", "e1"), claim("The trip lasts 3 nights.", "e2")
    n1, n2 = claim("The hotel stay costs $300.", "n1"), claim("The hotel costs $80 a night.", "n2")
    for c in (e1, e2):
        store.add("claims", c, "l1")
    for c in (n1, n2):
        store.add("claims", c, "l2")
    for c in (e1, e2):
        store.link("input_claim", "l2", c.id)
    return store, [e1, e2], [n1, n2]


def reply(*entries):
    return {"relations": [dict(zip(("new", "earlier", "relation"), e)) for e in entries]}


def test_relations_are_parsed_and_recorded_in_the_store():
    store, (e1, e2), (n1, n2) = session()
    llm = JsonLLM(reply(("N1", "E1", "contributes"), ("N1", "E2", "contributes"), ("N2", "E1", "conflict")))
    extractor = ClaimRelationExtractor(llm)

    relations = extractor.extract(store, [n1, n2])

    assert [(r.claim_id, r.other_id, r.relation) for r in relations] == [
        ("n1", "e1", "derived_from"),
        ("n1", "e2", "derived_from"),
        ("n2", "e1", "conflict"),
    ]
    assert store.related(DERIVED_FROM, "n1") == ["e1", "e2"]  # new claim -> input claim only
    assert store.related(DERIVED_FROM, "e1") == []
    assert store.related(CONFLICTS_WITH, "n2") == ["e1"]  # symmetric
    assert store.related(CONFLICTS_WITH, "e1") == ["n2"]
    assert store.related(SAME_AS, "n1") == []
    assert extractor.last_usage.calls == 1 and len(llm.prompts) == 1


def test_same_is_recorded_both_ways():
    store, _, (n1, n2) = session()
    ClaimRelationExtractor(JsonLLM(reply(("N2", "E1", "same")))).extract(store, [n1, n2])
    assert store.related(SAME_AS, "n2") == ["e1"] and store.related(SAME_AS, "e1") == ["n2"]


def test_the_prompt_lists_the_new_and_the_earlier_claims():
    store, (e1, e2), (n1, n2) = session()
    llm = JsonLLM(reply())
    ClaimRelationExtractor(llm).extract(store, [n1, n2])

    new_part, earlier_part = llm.prompts[0].split("=== EARLIER CLAIMS ===")
    assert "N1. The hotel stay costs $300." in new_part and "N2. The hotel costs $80 a night." in new_part
    assert "E1. The hotel costs $100 a night." in earlier_part and "E2. The trip lasts 3 nights." in earlier_part
    assert llm.prompts[0] == render_prompt([n1, n2], [e1, e2])


def test_no_input_claims_and_a_single_claim_means_no_request():
    store, _, _ = session()
    llm = JsonLLM()
    extractor = ClaimRelationExtractor(llm)

    assert extractor.extract(store, [store.get("e1").element]) == []
    assert llm.prompts == [] and extractor.last_usage.calls == 0


def test_the_new_claims_are_related_to_each_other_even_without_input_claims():
    store, (e1, e2), _ = session()  # the claims e1 and e2 were generated by l1, which has no input
    llm = JsonLLM(reply(("N2", "N1", "conflict")))
    extractor = ClaimRelationExtractor(llm)

    relations = extractor.extract(store, [e1, e2])

    assert "=== EARLIER CLAIMS ===\n(none)" in llm.prompts[0]
    assert [(r.claim_id, r.other_id, r.relation) for r in relations] == [("e2", "e1", "conflict")]
    assert store.related(CONFLICTS_WITH, "e1") == ["e2"] and store.related(CONFLICTS_WITH, "e2") == ["e1"]


def test_new_claims_are_related_to_input_claims_and_to_each_other_in_one_request():
    store, _, (n1, n2) = session()
    llm = JsonLLM(reply(("N2", "N1", "contributes"), ("N1", "E1", "contributes"), ("N2", "E1", "conflict")))
    extractor = ClaimRelationExtractor(llm)

    relations = extractor.extract(store, [n1, n2])

    assert len(llm.prompts) == 1
    assert [(r.claim_id, r.other_id, r.relation) for r in relations] == [
        ("n2", "n1", "derived_from"),
        ("n1", "e1", "derived_from"),
        ("n2", "e1", "conflict"),
    ]
    assert store.related(DERIVED_FROM, "n2") == ["n1"]  # n2 is derived from n1, not the reverse
    assert store.related(DERIVED_FROM, "n1") == ["e1"]


def test_a_claim_that_is_not_in_the_store_is_ignored():
    store, _, _ = session()
    llm = JsonLLM()
    assert ClaimRelationExtractor(llm).extract(store, [claim("unknown", "zz")]) == []
    assert llm.prompts == []


def test_one_request_per_node():
    store, _, (n1, n2) = session()
    e3, n3 = claim("The flight is at 9am.", "e3"), claim("The flight is at 10am.", "n3")
    store.add("claims", e3, "l3")
    store.add("claims", n3, "l4")
    store.link("input_claim", "l4", "e3")
    llm = JsonLLM(reply(), reply(("N1", "E1", "conflict")))
    extractor = ClaimRelationExtractor(llm)

    relations = extractor.extract(store, [n1, n2, n3])

    assert len(llm.prompts) == 2
    assert [(r.claim_id, r.other_id) for r in relations] == [("n3", "e3")]
    assert extractor.last_usage.calls == 2


def test_unknown_labels_and_relations_are_ignored():
    _, (e1, e2), (n1, n2) = session()
    data = reply(
        ("N9", "E1", "conflict"),
        ("N1", "E9", "conflict"),
        ("N1", "E1", "supports"),
        ("n1", " e2 ", "Contributes"),  # labels and relations are normalised
    )
    data["relations"].append("not an object")
    relations = parse_relations(data, [n1, n2], [e1, e2])
    assert [(r.claim_id, r.other_id, r.relation) for r in relations] == [("n1", "e2", "derived_from")]


def test_pairs_of_new_claims_are_deduplicated_and_a_claim_is_not_related_to_itself():
    _, (e1, e2), (n1, n2) = session()
    data = reply(
        ("N1", "N2", "conflict"),
        ("N2", "N1", "conflict"),  # the same pair, in the other order
        ("N1", "N1", "same"),  # itself
        ("N1", "N2", "same"),  # contradicts the conflict: both dropped
    )
    assert parse_relations(data, [n1, n2], [e1, e2]) == []
    data = reply(("N1", "N2", "conflict"), ("N2", "N1", "conflict"), ("N1", "N1", "same"))
    relations = parse_relations(data, [n1, n2], [e1, e2])
    assert [(r.claim_id, r.other_id, r.relation) for r in relations] == [("n1", "n2", "conflict")]


def test_derived_from_in_both_directions_between_two_new_claims_is_dropped():
    _, (e1, e2), (n1, n2) = session()
    data = reply(("N1", "N2", "contributes"), ("N2", "N1", "contributes"))
    assert parse_relations(data, [n1, n2], [e1, e2]) == []


def test_the_other_claim_can_also_be_given_as_earlier():
    _, (e1, e2), (n1, n2) = session()
    data = {"relations": [{"new": "N1", "earlier": "E1", "relation": "same"}]}
    assert [(r.claim_id, r.other_id) for r in parse_relations(data, [n1, n2], [e1, e2])] == [("n1", "e1")]


def test_a_pair_given_twice_counts_once_and_contradictory_relations_are_dropped():
    _, (e1, e2), (n1, n2) = session()
    data = reply(("N1", "E1", "conflict"), ("N1", "E1", "conflict"), ("N2", "E2", "same"), ("N2", "E2", "contributes"))
    relations = parse_relations(data, [n1, n2], [e1, e2])
    assert [(r.claim_id, r.other_id, r.relation) for r in relations] == [("n1", "e1", "conflict")]


def test_a_reply_without_a_relations_list_is_asked_again_once():
    store, _, (n1, n2) = session()
    llm = JsonLLM({"N1": "some comment"}, reply(("N1", "E1", "contributes")))
    extractor = ClaimRelationExtractor(llm)

    relations = extractor.extract(store, [n1, n2])

    assert [(r.claim_id, r.other_id) for r in relations] == [("n1", "e1")]
    assert len(llm.prompts) == 2 and "not valid" in llm.prompts[1] and "not valid" not in llm.prompts[0]
    assert extractor.last_usage.calls == 2


def test_the_partners_of_a_symmetric_relation_include_the_claims_of_the_node_in_both_directions():
    from symbolic_extractor import SymbolicExtractor
    from symbolic_extractor.relations import ClaimRelation

    relations = [
        ClaimRelation(claim_id="n2", other_id="n1", relation="conflict"),  # between two new claims
        ClaimRelation(claim_id="n2", other_id="e1", relation="conflict"),  # with an input claim
        ClaimRelation(claim_id="n1", other_id="e2", relation="same"),
    ]
    node = {"n1", "n2"}
    partners = SymbolicExtractor._partners
    assert partners(relations, "n1", node, "conflict") == ["n2"]
    assert partners(relations, "n2", node, "conflict") == ["n1", "e1"]
    assert partners(relations, "n1", node, "same") == ["e2"]
    assert partners(relations, "n2", node, "same") == []
    assert partners(relations, "e1", node, "conflict") == []  # not a claim of the node


def test_a_reply_that_is_not_json_is_asked_again_once():
    store, _, (n1, n2) = session()
    llm = JsonLLM(ValueError("No JSON object found in the LLM reply"), reply(("N1", "E1", "contributes")))
    extractor = ClaimRelationExtractor(llm)

    relations = extractor.extract(store, [n1, n2])

    assert [(r.claim_id, r.other_id) for r in relations] == [("n1", "e1")]
    assert len(llm.prompts) == 2 and "not valid" in llm.prompts[1]
    assert extractor.last_usage.calls == 1  # only the request that returned has a usage


def test_two_replies_that_are_not_json_are_a_failure():
    store, _, (n1, n2) = session()
    llm = JsonLLM(ValueError("bad"), ValueError("bad again"))
    with pytest.raises(ValueError, match="bad again"):
        ClaimRelationExtractor(llm).extract(store, [n1, n2])
    assert len(llm.prompts) == 2


def test_an_api_error_is_not_retried():
    store, _, (n1, n2) = session()
    llm = JsonLLM(ConnectionError("proxy down"), reply())
    with pytest.raises(ConnectionError):
        ClaimRelationExtractor(llm).extract(store, [n1, n2])
    assert len(llm.prompts) == 1


def test_two_replies_without_a_relations_list_are_a_failure_but_their_usage_is_counted():
    store, _, (n1, n2) = session()
    extractor = ClaimRelationExtractor(JsonLLM({"result": "none"}, {"N1": "x"}))
    with pytest.raises(ValueError):
        extractor.extract(store, [n1, n2])
    assert extractor.last_usage.calls == 2
    assert store.related(CONFLICTS_WITH, "n1") == []
